// Whose keys, settings, limits and storage a piece of work uses: one place for every edge function.
//
//   legacy / install   one tenant for everyone: the install-wide key reader (_shared/keys.ts: edge function
//                      secret first, then Vault), the install row's settings, the install's limits.
//                      Exactly what the functions did before accounts existed (one shared reader, so the
//                      same caching).
//   accounts           each account is its own tenant: its own keys only (Vault `acct:<user>:<NAME>`),
//                      its own settings (accounts.settings), its plan (account_limits), and the platform's
//                      limits (platform.settings.limits). A staff account may fall back to the platform's
//                      keys (environment, then install-wide Vault): source "platform". A non-staff account
//                      NEVER reads an environment variable, an install-wide Vault row, a model override
//                      from the environment, or another account's keys.
//
// Worker secrets, function addresses and the desktop runner's secret are the platform's in every mode:
// `platform()` is typed so only those names can be read through it. Everything else needs a Tenant, so
// `deno check` finds every place that would read a key without saying whose.
//
//   const tenancy = createTenancy(db);
//   const { id, tenant } = await tenancy.member(req);       // a request
//   const tenant = await tenancy.for(job.user_id);           // a worker, for the job's account
//   await tenant.keys.need("OPENAI_API_KEY");                 // "Add your OpenAI key in Settings > API keys."
import type { SupabaseClient } from "@supabase/supabase-js";
import { type AccountRow, type Auth, createAuth, HttpError, type Member, type Mode } from "./auth.ts";
import { createAccountKeys, createKeys, type Env, type Keys } from "./keys.ts";
import { type InstallLimits, type LimitEnv, platformSafetyGb, resolveLimits, resolvePlatformLimits } from "./limits.ts";
import { requestLocale, type UiLocale } from "./language.ts";
import { fullNote, type Room, storageRoom } from "./storage.ts";

export type { Mode };

/** What a plan allows (plans.limits merged with accounts.limits_override: account_limits in SQL). */
export interface PlanLimits { maxApps: number; storageGb: number; monthlyGenerations: number; jobConcurrency: number; maxOpenJobs: number }
export interface Plan { id: string; staff: boolean; limits: PlanLimits }

/** The free plan's numbers, used when the database can't say (never more generous than the free plan). */
export const FREE_PLAN_LIMITS: PlanLimits = { maxApps: 2, storageGb: 5, monthlyGenerations: 200, jobConcurrency: 2, maxOpenJobs: 100 };

export interface Tenant {
  mode: Mode;
  /** The account the work is for; null for install-wide work (a health check in install or legacy mode). */
  userId: string | null;
  /** A staff account (accounts mode): top limits, may fall back to the platform's keys. False elsewhere. */
  staff: boolean;
  /** False for a suspended account: its work is refused. Always true in install and legacy mode. */
  active: boolean;
  /** This tenant's keys (see the top of this file). */
  keys: Keys;
  /**
   * install.settings or accounts.settings, as stored. Undefined when there are none at all (a legacy
   * database, a staff account that never saved any), which keeps chooseProvider's older rule.
   */
  settings: Record<string, unknown> | undefined;
  /** The Supabase plan's limits: one invocation's time, the largest file, the project's storage. */
  limits: InstallLimits;
  /** The account's plan (accounts mode); null in install and legacy mode. */
  plan: Plan | null;
  /**
   * The language of the request this tenant serves (the studio's x-ui-locale header), for AI-written text
   * (language.ts). Set by member() and manager() only; a worker's tenant has none: use tenantLocale().
   */
  locale?: UiLocale | null;
}

/** The only names `platform()` reads: generated by migrations or setup, never an account's. */
export type PlatformSecretName =
  | "RADAR_WORKER_SECRET" | "LAUNCH_WORKER_SECRET" | "RESEARCH_WORKER_SECRET"
  | "RADAR_URL" | "CREATIVES_URL" | "LAUNCH_URL" | "RESEARCH_URL" | "METRICS_URL"
  | "CREATIVES_RUNNER_SECRET";

export interface PlatformSecrets {
  get(name: PlatformSecretName): Promise<string | undefined>;
  clear(): void;
}

/** Rate limits per account and action (accounts mode, non-staff): [window in seconds, most hits in it]. */
export const RATE_LIMITS = {
  "research.pull": [3600, 60],
  "research.scan": [3600, 60],
  "research.decode": [3600, 300],
  "research.import": [3600, 60],
  "radar.intake": [3600, 30],
  "radar.analyze": [3600, 20],
  "creatives.qa": [3600, 300],
  "creatives.copy": [3600, 200],
  "creatives.improve": [3600, 200],
  "metrics.sync": [3600, 30],
  "metrics.verify": [3600, 60],
  "install.keys": [3600, 60],
} as const satisfies Record<string, readonly [number, number]>;
export type RateBucket = keyof typeof RATE_LIMITS;

export const RATE_LIMITED = "That's a lot of requests in a short time. Wait a few minutes, then try again.";

export interface Tenancy {
  auth: Auth;
  mode(): Promise<Mode>;
  /** The tenant a piece of work for this user runs as. */
  for(userId: string): Promise<Tenant>;
  /** The signed-in caller (403 unless let in: _shared/auth.ts) and their tenant. */
  member(req: Request): Promise<Member & { tenant: Tenant }>;
  /** The caller who may change keys and settings (auth.manager) and their tenant. */
  manager(req: Request): Promise<Member & { tenant: Tenant }>;
  /**
   * For a /health answer: in install or legacy mode the install-wide tenant (no sign-in needed, as
   * before); in accounts mode the caller's tenant when the request carries a session, else null (the
   * answer is then only `{ ok, mode }`: no key of anyone's is described to a stranger).
   */
  healthTenant(req: Request): Promise<Tenant | null>;
  /** Worker secrets, function addresses, the desktop runner's secret. */
  platform(): PlatformSecrets;
  /**
   * The reader for work that was started with a known kind of key and must be finished with the same one
   * (a research pull polled later: ad_pulls.key_source). `account`: the account's own keys only.
   * `platform`: the platform's, for a staff account only (null for anyone else). null (a row from before
   * the column): the tenant's usual reader. In install and legacy mode always the tenant's reader.
   */
  keysFor(tenant: Tenant, source: "account" | "platform" | null): Keys | null;
  /** Which kind of key a tenant's reader would use for `name` now: for ad_pulls.key_source (null outside accounts mode or when unset). */
  keySource(tenant: Tenant, name: string): Promise<"account" | "platform" | null>;
  /** Room to store files for this tenant: the project's, and in accounts mode also the account's (the tighter). */
  room(tenant: Tenant): Promise<Room>;
  /** The note for a full store, in the words that fit whose storage is full. */
  fullNote(room: Room | null | undefined): string;
  /** Counts one hit of an action; 429 past the account's limit (accounts mode, non-staff only). Never fails closed. */
  rate(tenant: Tenant, bucket: RateBucket): Promise<void>;
  /** Which of these users may have scheduled work done (accounts mode: active accounts; elsewhere: all of them). */
  activeUsers(userIds: string[]): Promise<Set<string>>;
  /** Forget cached tenants (one account's, after it saved a key or a setting; or all). */
  clear(userId?: string): void;
}

export interface TenancyOptions {
  /** One environment variable (default: the function's own). */
  env?: Env;
  /** Every environment variable's name (default: the function's own). */
  envNames?: () => string[];
  /** An Auth over the same client (default: a new one). */
  auth?: Auth;
}

const TTL_MS = 60_000;
const MAX_TENANTS = 500;

const num = (value: unknown, fallback: number) => {
  // The same rule as limit_number() in SQL: a number, or a string that is only digits (with one decimal point).
  const n = typeof value === "string" ? (/^\s*[0-9]+(\.[0-9]+)?\s*$/.test(value) ? Number(value) : NaN) : value;
  return typeof n === "number" && Number.isFinite(n) && n >= 0 ? n : fallback;
};

/** account_limits' answer, every number present (the free plan's where it says nothing usable). */
export function readPlanLimits(raw: unknown): PlanLimits {
  const source = (raw && typeof raw === "object" && !Array.isArray(raw) ? raw : {}) as Record<string, unknown>;
  return {
    maxApps: num(source.maxApps, FREE_PLAN_LIMITS.maxApps),
    storageGb: num(source.storageGb, FREE_PLAN_LIMITS.storageGb),
    monthlyGenerations: num(source.monthlyGenerations, FREE_PLAN_LIMITS.monthlyGenerations),
    jobConcurrency: num(source.jobConcurrency, FREE_PLAN_LIMITS.jobConcurrency),
    maxOpenJobs: num(source.maxOpenJobs, FREE_PLAN_LIMITS.maxOpenJobs),
  };
}

/** An account's settings as a tenant sees them: none stored reads as undefined for staff (older AI rule), {} otherwise. */
export function accountSettings(account: Pick<AccountRow, "settings" | "staff">): Record<string, unknown> | undefined {
  if (Object.keys(account.settings).length) return account.settings;
  return account.staff ? undefined : {};
}

export function createTenancy(db: SupabaseClient, options: TenancyOptions = {}): Tenancy {
  const env: Env = options.env ?? ((name) => Deno.env.get(name));
  const envNames = options.envNames ?? (() => Object.keys(Deno.env.toObject()));
  const limitEnv: LimitEnv = (name) => env(name);
  const auth = options.auth ?? createAuth(db);
  /** The install-wide reader: everyone's in install and legacy mode, the platform's in accounts mode. */
  const shared = createKeys(db, env, envNames);
  const tenants = new Map<string, { at: number; tenant: Tenant }>();
  // The account-only readers keysFor hands out, by account (not by tenant object: member() returns a
  // per-request copy of the cached tenant carrying the request's language), kept as long as a tenant.
  const own = new Map<string, { reader: Keys; at: number }>();

  async function installWide(userId: string | null, mode: Mode): Promise<Tenant> {
    const install = await auth.install();
    return { mode, userId, staff: false, active: true, keys: shared, settings: install?.settings, limits: resolveLimits(install, limitEnv), plan: null };
  }

  async function forUser(userId: string): Promise<Tenant> {
    const mode = await auth.mode();
    if (mode !== "accounts") return installWide(userId, mode);
    const hit = tenants.get(userId);
    if (hit && Date.now() - hit.at < TTL_MS) return hit.tenant;
    const account = await auth.account(userId);
    if (!account) return installWide(userId, await auth.mode());
    const { data, error } = await db.rpc("account_limits", { p_user: userId });
    const tenant: Tenant = {
      mode, userId, staff: account.staff, active: account.status === "active",
      keys: createAccountKeys(db, userId, account.staff ? shared : null),
      settings: accountSettings(account),
      limits: resolvePlatformLimits(await auth.platform(), limitEnv),
      plan: { id: account.plan, staff: account.staff, limits: readPlanLimits(error ? null : data) },
    };
    if (tenants.size >= MAX_TENANTS) tenants.delete(tenants.keys().next().value!);
    tenants.set(userId, { at: Date.now(), tenant });
    return tenant;
  }

  return {
    auth,
    mode: () => auth.mode(),
    for: forUser,
    // A copy per request (tenants are cached per account), carrying this request's language.
    async member(req) {
      const caller = await auth.member(req);
      return { ...caller, tenant: { ...(await forUser(caller.id)), locale: requestLocale(req) } };
    },
    async manager(req) {
      const caller = await auth.manager(req);
      return { ...caller, tenant: { ...(await forUser(caller.id)), locale: requestLocale(req) } };
    },
    async healthTenant(req) {
      const mode = await auth.mode();
      if (mode !== "accounts") return installWide(null, mode);
      if (!req.headers.get("Authorization")?.replace(/^Bearer\s+/i, "")) return null;
      return (await this.member(req)).tenant;
    },
    platform: () => ({ get: (name: PlatformSecretName) => shared.get(name), clear: () => shared.clear() }),
    keysFor(tenant, source) {
      if (tenant.mode !== "accounts" || !tenant.userId || source === null) return tenant.keys;
      if (source === "platform") return tenant.staff ? shared : null;
      const hit = own.get(tenant.userId);
      if (hit && Date.now() - hit.at < TTL_MS) return hit.reader;
      const reader = createAccountKeys(db, tenant.userId, null);
      own.set(tenant.userId, { reader, at: Date.now() });
      return reader;
    },
    async keySource(tenant, name) {
      if (tenant.mode !== "accounts") return null;
      const source = await tenant.keys.source(name);
      return source === "platform" ? "platform" : source ? "account" : null;
    },
    async room(tenant) {
      if (tenant.mode !== "accounts") return storageRoom(db, tenant.limits, null);
      // Accounts mode: each account's plan is the real limit; the whole project's check is only a safety
      // net set much higher (platform.settings.safetyStorageGb), so one account's files can't block everyone.
      const account = tenant.userId && tenant.plan ? { userId: tenant.userId, storageGb: tenant.plan.limits.storageGb } : null;
      return storageRoom(db, { storageQuotaGb: platformSafetyGb(await auth.platform()) }, account);
    },
    fullNote: (room) => fullNote(room),
    async rate(tenant, bucket) {
      if (tenant.mode !== "accounts" || tenant.staff || !tenant.userId) return;
      const [windowSec, max] = RATE_LIMITS[bucket];
      const { data, error } = await db.rpc("account_rate_hit", { p_user: tenant.userId, p_bucket: bucket, p_window_sec: windowSec, p_max: max });
      if (!error && data === false) throw new HttpError(429, RATE_LIMITED);
    },
    async activeUsers(userIds) {
      const ids = [...new Set(userIds)];
      if (await auth.mode() !== "accounts" || !ids.length) return new Set(ids);
      // A user with no account row yet is active (account_ensure would make one, active).
      const active = new Set(ids);
      for (let i = 0; i < ids.length; i += 200) {
        const { data, error } = await db.from("accounts").select("user_id, status").in("user_id", ids.slice(i, i + 200));
        if (error) throw new HttpError(503, "Couldn't check the accounts. Try again in a moment.");
        for (const row of (data ?? []) as { user_id: string; status: string }[]) if (row.status !== "active") active.delete(row.user_id);
      }
      return active;
    },
    clear(userId) {
      if (userId) {
        tenants.get(userId)?.tenant.keys.clear();
        tenants.delete(userId);
        own.get(userId)?.reader.clear();
        own.delete(userId);
        auth.clear(userId);
        return;
      }
      for (const { tenant } of tenants.values()) tenant.keys.clear();
      tenants.clear();
      for (const { reader } of own.values()) reader.clear();
      own.clear();
      shared.clear();
      auth.clear();
    },
  };
}
