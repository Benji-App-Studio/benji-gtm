-- The install: who owns this copy, its settings, and its API keys.
--
-- Until now every third-party key was an edge function secret set by hand in the Supabase dashboard,
-- and anyone who signed up could use them. This migration lets the app manage both:
--   * install            one row once setup has run: the owner and the install's settings.
--   * install_members    who may use this install (the owner, and anyone the owner adds).
--   * Vault              holds the API keys, written by install_put_secret and read by install_secrets.
--   * install_secrets_meta  what the Settings page may show about a key (last 4 characters, when it was
--                        checked): never the key itself.
--   * install_migrations the ledger the setup wizard keeps, so updates apply only what is new.
--
-- An install with no `install` row (one set up before this migration) keeps working as before: keys
-- from edge function secrets, access by the existing email allow-lists.

-- MARK: Ledger

-- Created by the setup wizard before the first migration runs; here so every database has it.
create table if not exists public.install_migrations (
  version text primary key,
  name text not null,
  sha256 text not null,
  applied_at timestamptz not null default now()
);
alter table public.install_migrations enable row level security;

-- MARK: Install, members

create table public.install (
  id boolean primary key default true check (id),
  owner_user_id uuid references auth.users (id) on delete set null,
  -- { name?, aiProvider?: "openai" | "typesafe", models?: {...}, limits?: {...} }
  settings jsonb not null default '{}'::jsonb,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);
alter table public.install enable row level security;
create trigger install_touch before update on public.install for each row execute function public.touch_updated_at();

create table public.install_members (
  user_id uuid primary key references auth.users (id) on delete cascade,
  role text not null default 'member' check (role in ('owner', 'member')),
  created_at timestamptz not null default now()
);
alter table public.install_members enable row level security;
-- A signed-in person can see their own membership (the app shows owner-only pages from it).
create policy install_members_self on public.install_members for select to authenticated using (user_id = (select auth.uid()));

-- MARK: Keys

create table public.install_secrets_meta (
  name text primary key,
  last4 text,
  set_at timestamptz not null default now(),
  verified_at timestamptz,
  status text not null default 'unverified' check (status in ('ok', 'failed', 'unverified')),
  message text
);
alter table public.install_secrets_meta enable row level security;

-- The names a key may be stored under. Worker secrets and function addresses are not in this list:
-- they are generated by migrations and never set by a person.
create function public.install_secret_allowed(p_name text) returns boolean
language sql immutable set search_path = '' as $$
  select p_name in (
    'OPENAI_API_KEY', 'TYPESAFE_API_KEY', 'APIFY_TOKEN',
    'META_AD_LIBRARY_TOKEN', 'META_SYSTEM_USER_TOKEN', 'META_APP_SECRET',
    'REVENUECAT_API_KEY', 'APPSTACK_API_KEY', 'HIGGSFIELD_API_KEY',
    'GOOGLE_SERVICE_ACCOUNT_JSON', 'CREATIVES_RUNNER_SECRET',
    'TIKTOK_RESEARCH_CLIENT_KEY', 'TIKTOK_RESEARCH_CLIENT_SECRET'
  ) or p_name ~ '^APPSTACK_API_KEY_[A-Za-z0-9_]{1,64}$';
$$;

-- Stores (or replaces) one key in Vault and notes its last 4 characters for the Settings page.
create function public.install_put_secret(p_name text, p_value text) returns void
language plpgsql security definer set search_path = '' as $$
declare existing uuid; clean text := btrim(p_value);
begin
  if not public.install_secret_allowed(p_name) then raise exception 'Unknown key name %', p_name; end if;
  if clean is null or clean = '' then raise exception 'The key is empty'; end if;
  select id into existing from vault.secrets where name = p_name;
  if existing is null then
    perform vault.create_secret(clean, p_name);
  else
    perform vault.update_secret(existing, clean);
  end if;
  insert into public.install_secrets_meta (name, last4, set_at, verified_at, status, message)
  values (p_name, right(clean, 4), now(), null, 'unverified', null)
  on conflict (name) do update set last4 = excluded.last4, set_at = excluded.set_at, verified_at = null, status = 'unverified', message = null;
end;
$$;

create function public.install_delete_secret(p_name text) returns void
language plpgsql security definer set search_path = '' as $$
begin
  if not public.install_secret_allowed(p_name) then raise exception 'Unknown key name %', p_name; end if;
  delete from vault.secrets where name = p_name;
  delete from public.install_secrets_meta where name = p_name;
end;
$$;

-- Notes the result of a live check of a key (the edge function calls the provider, then this).
create function public.install_mark_secret(p_name text, p_ok boolean, p_message text default null) returns void
language sql security definer set search_path = '' as $$
  update public.install_secrets_meta
     set status = case when p_ok then 'ok' else 'failed' end,
         verified_at = now(),
         message = left(p_message, 300)
   where name = p_name;
$$;

-- Every key and setting the edge functions read from Vault: the keys a person set, the worker
-- secrets and the function addresses. One reader for all functions (supabase/functions/_shared/keys.ts).
create function public.install_secrets() returns table (name text, value text)
language sql security definer set search_path = '' as $$
  select s.name, s.decrypted_secret from vault.decrypted_secrets s
   where public.install_secret_allowed(s.name)
      or s.name in ('OPENAI_MODEL',
                    'RADAR_WORKER_SECRET', 'LAUNCH_WORKER_SECRET', 'RESEARCH_WORKER_SECRET',
                    'RADAR_URL', 'CREATIVES_URL', 'LAUNCH_URL', 'RESEARCH_URL', 'METRICS_URL');
$$;

-- MARK: Function addresses

-- The cron jobs wake the edge functions at addresses kept in Vault. Earlier migrations wrote the
-- first project's address there; setup calls this with the project's own
-- (https://<ref>.supabase.co/functions/v1) so each install wakes its own functions.
create function public.install_set_function_urls(p_base text) returns void
language plpgsql security definer set search_path = '' as $$
declare base text := regexp_replace(btrim(p_base), '/+$', ''); pair record; existing uuid;
begin
  if base !~ '^https?://[^[:space:]/]+(:[0-9]+)?(/[^[:space:]]*)?$' then raise exception 'Not a function address: %', p_base; end if;
  for pair in select * from (values
    ('RADAR_URL', 'radar'), ('CREATIVES_URL', 'creatives'), ('LAUNCH_URL', 'launch'),
    ('RESEARCH_URL', 'research'), ('METRICS_URL', 'metrics')) as t(name, fn)
  loop
    select id into existing from vault.secrets where name = pair.name;
    if existing is null then
      perform vault.create_secret(base || '/' || pair.fn, pair.name);
    else
      perform vault.update_secret(existing, base || '/' || pair.fn);
    end if;
  end loop;
end;
$$;

-- MARK: Scheduled sync for Measure (written out but never scheduled until now)

-- Every six hours the metrics function syncs every workspace with a connection. It does nothing when
-- no keys are set, so it is safe to schedule on every install that has an owner; older installs
-- schedule it by hand as before (see 20261002200000_measure.sql).
create function public.metrics_call(p_route text) returns void
language plpgsql security definer set search_path = '' as $$
declare url text; secret text;
begin
  if p_route not in ('sync-all') then raise exception 'Unknown route %', p_route; end if;
  select decrypted_secret into url from vault.decrypted_secrets where name = 'METRICS_URL';
  select decrypted_secret into secret from vault.decrypted_secrets where name = 'RADAR_WORKER_SECRET';
  if url is null or secret is null then return; end if;
  perform net.http_post(
    url := url || '/' || p_route,
    headers := jsonb_build_object('Content-Type', 'application/json', 'x-radar-worker', secret),
    body := '{}'::jsonb,
    timeout_milliseconds := 10000
  );
end;
$$;

-- Turns the optional schedules on (setup calls this once the install has an owner).
create function public.install_schedule_optional_jobs() returns void
language plpgsql security definer set search_path = '' as $$
begin
  perform cron.schedule('measure-sync', '23 */6 * * *', 'select public.metrics_call(''sync-all'')');
  perform cron.schedule('launch-daily', '0 4 * * *', 'select public.launch_call(''daily'')');
end;
$$;

