/** A list of English labels ("Website or App") → the same list in the page's language. */
function list(tr: Translator, text: string, sep: string, type: "conjunction" | "disjunction"): string {
  const parts = text.split(sep).map((p) => tr.t(p.trim()));
  try { return new Intl.ListFormat(tr.intl, { style: "long", type }).format(parts); }
  catch { return parts.join(sep); }
}

