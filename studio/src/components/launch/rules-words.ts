/**
 * A label, hint or message from rules.ts (or the launch function, which says the same things) in the
 * page's language. Anything it doesn't know stays as written.
 */
export function ruleText(tr: Translator, text: string): string {
  const exact = tr.t(text);
  if (exact !== text) return exact;
  for (const [pattern, say] of PATTERNS) {
    const match = pattern.exec(text);
    if (match) return say(tr, ...match.slice(1));
  }
  return text;
}
